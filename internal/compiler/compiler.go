// Package compiler turns a validated config into one nftables ruleset that
// is loaded atomically with `nft -f`.
//
// Phase 1 scope: IPv4, zones, static and tag-based address groups,
// tcp/udp/icmp services, allow/deny/reset, logging. Rules that match on
// applications are skipped with a warning until App Identification lands in phase 2.
package compiler

import (
	"fmt"
	"net/netip"
	"regexp"
	"slices"
	"sort"
	"strconv"
	"strings"
	"time"

	"github.com/stevejboyle/hobby-ngfw/internal/config"

	"github.com/stevejboyle/hobby-ngfw/internal/appid"
)

// Table is the nftables table this firewall owns. Nothing else touches it.
const Table = "inet ngfw"

// TagEntry is one IP currently registered with a tag.
type TagEntry struct {
	IP        netip.Addr
	Remaining time.Duration // 0 means no expiry
}

// Result is a compiled ruleset.
type Result struct {
	Ruleset  string
	Warnings []string
	// Sets maps each tag used by a dynamic address group to its nft set name.
	Sets map[string]string
	// IfAddrSets maps an interface to the set holding its live addresses
	// (hairpin NAT of a port-forward on an interface with no configured
	// address); ngfwd fills them.
	IfAddrSets map[string]string
}

// Compile builds the ruleset. cfg must already be validated. tags is the
// current registry snapshot; its entries are written into the dynamic sets
// in the same transaction, so a commit never drops live tag registrations.
func Compile(cfg *config.Config, tags map[string][]TagEntry) (*Result, error) {
	c := &compiler{cfg: cfg, res: &Result{Sets: map[string]string{}, IfAddrSets: map[string]string{}}}
	if err := c.index(); err != nil {
		return nil, err
	}
	var b strings.Builder
	b.WriteString("# Generated by hobby-ngfw. Do not edit; changes are replaced on commit.\n")
	fmt.Fprintf(&b, "table %s\ndelete table %s\n", Table, Table)
	fmt.Fprintf(&b, "table %s {\n", Table)

	for _, tag := range sortedKeys(c.res.Sets) {
		fmt.Fprintf(&b, "\tset %s {\n\t\ttype ipv4_addr\n\t\tflags timeout\n", c.res.Sets[tag])
		fmt.Fprintf(&b, "\t\tcomment \"tag:%s\"\n", tag)
		if els := elements(tags[tag]); els != "" {
			fmt.Fprintf(&b, "\t\telements = { %s }\n", els)
		}
		b.WriteString("\t}\n\n")
	}

	if cfg.System.AppIDOn() {
		// App Identification: the first packets of each TCP/UDP connection go to
		// appidd until it marks the connection classified (ct mark bit
		// 12). bypass: with appidd down, packets go straight on.
		b.WriteString("\tchain appid {\n")
		b.WriteString("\t\ttype filter hook forward priority filter - 10; policy accept;\n")
		fmt.Fprintf(&b, "\t\tmeta nfproto ipv4 meta l4proto { tcp, udp } ct mark and 0x%x == 0 queue flags bypass,fanout to 0-1 comment \"app-identification\"\n", AppDoneBit)
		b.WriteString("\t}\n\n")
	}

	// App policy: with rules that name applications, a connection goes
	// through the rule base until its application is settled (appidd's
	// done bit), so a rule can act on the app (an "app shift"); then
	// an allowed connection takes the fast path (final bit).
	c.firstApp = -1
	if cfg.System.AppIDOn() {
		for i, r := range cfg.Rules {
			if !isAny(r.Application) {
				c.firstApp = i
				break
			}
		}
	}
	c.appMode = c.firstApp >= 0
	if c.appMode {
		b.WriteString("\tchain allowed {\n")
		b.WriteString("\t\t# App policy: an allowed connection becomes final (fast path) once its\n")
		b.WriteString("\t\t# application is settled, or at once if App Identification doesn't classify it.\n")
		fmt.Fprintf(&b, "\t\tct mark and 0x%x == 0x%x ct mark set ct mark or 0x%x accept\n", AppDoneBit, AppDoneBit, FinalBit)
		fmt.Fprintf(&b, "\t\tmeta l4proto != { tcp, udp } ct mark set ct mark or 0x%x accept\n", FinalBit)
		b.WriteString("\t\taccept\n")
		b.WriteString("\t}\n\n")
	}

	b.WriteString("\tchain forward {\n")
	b.WriteString("\t\ttype filter hook forward priority filter; policy drop;\n")
	if c.appMode {
		fmt.Fprintf(&b, "\t\tct mark and 0x%x == 0x%x drop comment \"app-identification: denied once identified\"\n", DeniedBit, DeniedBit)
		fmt.Fprintf(&b, "\t\tct state established ct mark and 0x%x == 0x%x accept\n", FinalBit, FinalBit)
		// Replies of a connection the rules let through (not denied: that's
		// above) pass; the rules judge the original direction.
		b.WriteString("\t\tct state established ct direction reply accept\n")
		fmt.Fprintf(&b, "\t\tct state related ct mark set ct mark or 0x%x accept\n", FinalBit)
	} else {
		if cfg.IPSActive() {
			fmt.Fprintf(&b, "\t\tct mark and 0x%x == 0x%x drop comment \"ips: blocked connection\"\n", DeniedBit, DeniedBit)
		}
		b.WriteString("\t\tct state established,related accept\n")
	}
	b.WriteString("\t\tct state invalid drop\n")
	c.trunkDrop(&b, true)
	for i, r := range cfg.Rules {
		for _, above := range cfg.Rules[:i] {
			if covers(above, r) {
				c.res.Warnings = append(c.res.Warnings,
					fmt.Sprintf("rule %q never matches: rule %q above it matches everything it would (move it up)", r.Name, above.Name))
				break
			}
		}
		c.ruleIdx = i
		lines, err := c.rule(r)
		if err != nil {
			return nil, err
		}
		if r.Action == "allow" && r.IPSProfile != "" {
			if cfg.IPSActive() {
				c.ipsRules = append(c.ipsRules, ipsRule{tag: (i + 1) << RuleShift, profile: r.IPSProfile})
			} else {
				c.res.Warnings = append(c.res.Warnings, fmt.Sprintf("rule %q: IPS is off (system ips), so its ips_profile %q is not applied", r.Name, r.IPSProfile))
			}
		}
		for _, l := range lines {
			b.WriteString("\t\t" + l + "\n")
		}
	}
	b.WriteString("\t\tcounter comment \"default-deny\"\n")
	b.WriteString("\t}\n")
	c.ips(&b)

	c.input(&b)
	c.ctZones(&b)
	if err := c.decrypt(&b); err != nil {
		return nil, err
	}

	c.natChains(&b)
	b.WriteString("}\n")

	c.res.Ruleset = b.String()
	return c.res, nil
}

// App Identification's use of the conntrack mark. appidd writes bits 0-12; the ruleset
// writes the rest:
//
//	bits  0-10  application ID (0 = not known yet, or unknown once done)
//	bit     11  log the session's end (logged allow rules; appidd)
//	bit     12  classification done (appidd)
//	bit     13  final: allowed with its application settled; fast path
//	bit     14  denied once its application was identified; dropped
//	bit     15  start already logged (logged allow rules log once)
//	bits 16-31  rule position + 1 (logged allow rules and rules with an IPS
//	            profile: appidd's end log, the IPS queue and its verdicts)
//
// The IPS (Suricata) marks packets it raises an alert on with the
// severity of the signature, in the packet mark (IPSMarkMask); the
// ips_enforce chain acts on that per the rule's profile and clears it.
const (
	AppMask    = 0x07ff
	SessionBit = 0x0800
	AppDoneBit = 0x1000
	FinalBit   = 0x2000
	DeniedBit  = 0x4000
	LoggedBit  = 0x8000
	RuleShift  = 16

	IPSCritical      = 0x01000000
	IPSMajor         = 0x02000000
	IPSMinor         = 0x04000000
	IPSInformational = 0x08000000
	IPSMarkMask      = 0x0f000000

	// AppPendingPackets caps how many packets (both directions) a rule that
	// names applications lets through while the application isn't known yet.
	// appidd settles every connection within its first 32 packets (MAX_PKTS
	// in appidd.c); past this cap the connection counts as unidentified, so
	// when appidd is stopped or overloaded (its queue bypassed) an
	// application-restricted allow can't turn into an unrestricted one.
	AppPendingPackets = 40
)

// IPSSeverityMark is the packet mark bit for a severity.
func IPSSeverityMark(severity string) uint32 {
	switch severity {
	case "critical":
		return IPSCritical
	case "major":
		return IPSMajor
	case "minor":
		return IPSMinor
	default:
		return IPSInformational
	}
}

// keepLow keeps the ct mark's low bits except the session-log bit when a
// rule re-tags a connection.
const keepLow = 0x0000ffff &^ SessionBit

// ipsRule is an allow rule with an IPS profile: its ct mark tag and profile.
type ipsRule struct {
	tag     int
	profile string
}

type compiler struct {
	cfg        *config.Config
	ruleIdx    int       // position of the rule being compiled
	appMode    bool      // some rule names applications (and App Identification is on)
	firstApp   int       // position of the first such rule (-1: none)
	ipsRules   []ipsRule // rules whose traffic the IPS inspects
	res        *Result
	zoneIfaces map[string][]string
	// inVRF holds interfaces in a non-default VRF. For their traffic the
	// forward and input hooks see the VRF device as iif, so they are matched
	// with meta sdifname, and in NAT postrouting (where sdif isn't available)
	// by the mark the raw prerouting chain gives them (vrfMark).
	inVRF    map[string]bool
	vrfMark  map[string]int
	addrs    map[string]string // address name -> prefix
	groups   map[string]config.AddressGroup
	services map[string]config.Service
}

var unsafe = regexp.MustCompile(`[^A-Za-z0-9_]`)

// vrfMarkBase keeps SJB-OS's per-interface marks out of the low bits.
const vrfMarkBase = 0x10000

func (c *compiler) index() error {
	c.zoneIfaces = map[string][]string{}
	c.inVRF = map[string]bool{}
	c.vrfMark = map[string]int{}
	for i, in := range c.cfg.Interfaces {
		if in.Zone != "" {
			c.zoneIfaces[in.Zone] = append(c.zoneIfaces[in.Zone], in.Name)
		}
		if v := in.VRFOf(); v != config.VRFDefault && v != config.VRFMgmt {
			c.inVRF[in.Name] = true
			c.vrfMark[in.Name] = vrfMarkBase + i + 1
		}
	}
	c.addrs = map[string]string{}
	for _, a := range c.cfg.Addresses {
		p, err := prefix(a.CIDR)
		if err != nil {
			return fmt.Errorf("address %q: %w", a.Name, err)
		}
		c.addrs[a.Name] = p
	}
	c.groups = map[string]config.AddressGroup{}
	used := map[string]bool{}
	tags := []string{}
	for _, g := range c.cfg.AddressGroups {
		c.groups[g.Name] = g
		if g.Tag != "" && !contains(tags, g.Tag) {
			tags = append(tags, g.Tag)
		}
	}
	sort.Strings(tags)
	for _, t := range tags {
		name := "dag_" + unsafe.ReplaceAllString(t, "_")
		for i := 2; used[name]; i++ {
			name = fmt.Sprintf("dag_%s_%d", unsafe.ReplaceAllString(t, "_"), i)
		}
		used[name] = true
		c.res.Sets[t] = name
	}
	c.services = map[string]config.Service{}
	for _, s := range c.cfg.Services {
		c.services[s.Name] = s
	}
	return nil
}

// addrTerm is one way to match a set of addresses: a literal set of
// prefixes, or a reference to a dynamic tag set.
type addrTerm struct {
	static []string
	set    string
}

func (t addrTerm) expr(field string) string {
	if t.set != "" {
		return fmt.Sprintf("ip %s @%s", field, t.set)
	}
	if len(t.static) == 1 {
		return fmt.Sprintf("ip %s %s", field, t.static[0])
	}
	return fmt.Sprintf("ip %s { %s }", field, strings.Join(t.static, ", "))
}

// addrTerms resolves a source/destination list. nil means match any.
func (c *compiler) addrTerms(names []string) []*addrTerm {
	if isAny(names) {
		return []*addrTerm{nil}
	}
	var static []string
	var terms []*addrTerm
	for _, n := range names {
		if p, ok := c.addrs[n]; ok {
			static = appendUnique(static, p)
			continue
		}
		g := c.groups[n]
		if g.Tag != "" {
			terms = append(terms, &addrTerm{set: c.res.Sets[g.Tag]})
			continue
		}
		for _, m := range g.Static {
			static = appendUnique(static, c.addrs[m])
		}
	}
	if len(static) > 0 {
		terms = append([]*addrTerm{{static: static}}, terms...)
	}
	return terms
}

// svcTerm matches one protocol and, for tcp/udp, its ports. nil means any.
type svcTerm struct {
	proto string
	ports []string
}

func (t svcTerm) expr() string {
	if t.proto == "icmp" {
		return "meta l4proto icmp"
	}
	ports := strings.Join(t.ports, ", ")
	if len(t.ports) > 1 {
		ports = "{ " + ports + " }"
	}
	return fmt.Sprintf("meta l4proto %s th dport %s", t.proto, ports)
}

func (c *compiler) svcTerms(names []string) []*svcTerm {
	if isAny(names) {
		return []*svcTerm{nil}
	}
	byProto := map[string]*svcTerm{}
	var order []string
	for _, n := range names {
		s := c.services[n]
		t, ok := byProto[s.Protocol]
		if !ok {
			t = &svcTerm{proto: s.Protocol}
			byProto[s.Protocol] = t
			order = append(order, s.Protocol)
		}
		for _, p := range strings.Split(s.Ports, ",") {
			if p = strings.TrimSpace(p); p != "" {
				t.ports = appendUnique(t.ports, p)
			}
		}
	}
	terms := make([]*svcTerm, 0, len(order))
	for _, p := range order {
		terms = append(terms, byProto[p])
	}
	return terms
}

func (c *compiler) zoneExpr(field string, zones []string) (string, bool) {
	if isAny(zones) {
		return "", true
	}
	var ifs []string
	for _, z := range zones {
		for _, i := range c.zoneIfaces[z] {
			ifs = appendUnique(ifs, fmt.Sprintf("%q", i))
		}
	}
	switch len(ifs) {
	case 0:
		return "", false
	case 1:
		return field + " " + ifs[0], true
	}
	return fmt.Sprintf("%s { %s }", field, strings.Join(ifs, ", ")), true
}

// set formats one value or a { set }.
func set(vals []string) string {
	if len(vals) == 1 {
		return vals[0]
	}
	return "{ " + strings.Join(vals, ", ") + " }"
}

// ingress returns the alternative match expressions for traffic arriving
// in any of zones: iifname for default-VRF interfaces, meta sdifname for
// interfaces in a VRF. [""] means any; nil means the zones have no
// interfaces. mark selects the NAT form (meta mark instead of sdifname).
func (c *compiler) ingress(zones []string, mark bool) []string {
	if isAny(zones) {
		return []string{""}
	}
	var plain, vrf []string
	for _, z := range zones {
		for _, i := range c.zoneIfaces[z] {
			switch {
			case !c.inVRF[i]:
				plain = appendUnique(plain, fmt.Sprintf("%q", i))
			case mark:
				vrf = appendUnique(vrf, fmt.Sprintf("0x%x", c.vrfMark[i]))
			default:
				vrf = appendUnique(vrf, fmt.Sprintf("%q", i))
			}
		}
	}
	var out []string
	if len(plain) > 0 {
		out = append(out, "iifname "+set(plain))
	}
	if len(vrf) > 0 {
		if mark {
			out = append(out, "meta mark "+set(vrf))
		} else {
			out = append(out, "meta sdifname "+set(vrf))
		}
	}
	return out
}

func (c *compiler) rule(r config.Rule) ([]string, error) {
	var appMatches []string
	if !isAny(r.Application) {
		if !c.cfg.System.AppIDOn() {
			c.res.Warnings = append(c.res.Warnings,
				fmt.Sprintf("rule %q skipped: it names applications but App Identification is off (set system app-identification on)", r.Name))
			return []string{fmt.Sprintf("# rule %q skipped: App Identification is off", r.Name)}, nil
		}
		var err error
		if appMatches, err = appTerms(c.expandApps(r.Application)); err != nil {
			return nil, fmt.Errorf("rule %q: %w", r.Name, err)
		}
	}
	froms := c.ingress(r.From, false)
	to, ok2 := c.zoneExpr("oifname", r.To)
	if len(froms) == 0 || !ok2 {
		c.res.Warnings = append(c.res.Warnings,
			fmt.Sprintf("rule %q skipped: a zone it uses has no interfaces", r.Name))
		return []string{fmt.Sprintf("# rule %q skipped: zone without interfaces", r.Name)}, nil
	}

	// Zone matches: one pair per ingress form, plus the decryption loop's
	// form of the same zones (see decrypt.go) when traffic is decrypted.
	type zonePair struct{ from, to string }
	var pairs []zonePair
	for _, from := range froms {
		pairs = append(pairs, zonePair{from, to})
	}
	if c.decryptOn() && !(isAny(r.From) && isAny(r.To)) {
		if in, out, ok := c.loopZones(r.From, r.To); ok {
			pairs = append(pairs, zonePair{in, out})
		}
	}
	var lines []string
	for _, zp := range pairs {
		from, to := zp.from, zp.to
		for _, src := range c.addrTerms(r.Source) {
			for _, dst := range c.addrTerms(r.Destination) {
				for _, svc := range c.svcTerms(r.Service) {
					for _, v := range verdicts(r.Action, svc) {
						parts := []string{}
						for _, p := range []string{from, to} {
							if p != "" {
								parts = append(parts, p)
							}
						}
						if src != nil {
							parts = append(parts, src.expr("saddr"))
						}
						if dst != nil {
							parts = append(parts, dst.expr("daddr"))
						}
						if svc != nil {
							parts = append(parts, svc.expr())
						}
						if v.match != "" {
							parts = append(parts, v.match)
						}
						if c.appMode {
							lines = append(lines, c.appModeLines(r, parts, v, appMatches)...)
							continue
						}
						parts = append(parts, "counter")
						if r.Log {
							parts = append(parts, fmt.Sprintf("log prefix \"ngfw %s %s \"", r.Name, r.Action))
						}
						if tag := c.ruleTag(r); tag != 0 {
							// Tag the connection with the rule (its position
							// + 1): appidd's end-of-session log, the IPS.
							parts = append(parts, fmt.Sprintf("ct mark set ct mark and 0x%08x or 0x%08x", keepLow, tag))
						}
						parts = append(parts, v.verdict, fmt.Sprintf("comment \"rule:%s\"", r.Name))
						lines = append(lines, strings.Join(parts, " "))
					}
				}
			}
		}
	}
	return lines, nil
}

// covers reports whether rule a (earlier) matches every connection rule b
// would, so b can never match: each of a's fields is any or lists all of
// b's names. It doesn't expand groups, so it may miss some shadowing, never
// report a false one.
func covers(a, b config.Rule) bool {
	sup := func(x, y []string) bool {
		if isAny(x) {
			return true
		}
		if isAny(y) {
			return false
		}
		for _, v := range y {
			if !slices.ContainsFunc(x, func(w string) bool { return strings.EqualFold(w, v) }) {
				return false
			}
		}
		return true
	}
	return sup(a.From, b.From) && sup(a.To, b.To) && sup(a.Source, b.Source) && sup(a.Destination, b.Destination) &&
		sup(a.Service, b.Service) && sup(a.Application, b.Application)
}

// expandApps replaces application groups with their members and
// categories ("category:video") with their applications.
func (c *compiler) expandApps(apps []string) []string {
	groups := map[string][]string{}
	for _, g := range c.cfg.ApplicationGroups {
		groups[g.Name] = g.Members
	}
	var out []string
	var add func(names []string)
	add = func(names []string) {
		for _, n := range names {
			if m, ok := groups[n]; ok {
				add(m) // groups hold applications and categories only
				continue
			}
			if catApps, ok := appid.CategoryApps(n); ok {
				for _, a := range catApps {
					out = append(out, a.Name)
				}
				continue
			}
			out = append(out, n)
		}
	}
	add(apps)
	return out
}

// appTerms turns rule applications into ct mark matches: one set of app IDs
// (provisional or final, so a TLS connection matches YouTube as soon as its
// server name is seen), and "unknown" as app 0 with classification done.
func appTerms(apps []string) ([]string, error) {
	var ids []int
	unknown := false
	for _, a := range apps {
		if strings.EqualFold(a, appid.Unknown) {
			unknown = true
			continue
		}
		app, ok := appid.Lookup(a)
		if !ok {
			return nil, fmt.Errorf("unknown application %q", a)
		}
		if !slices.Contains(ids, app.ID) {
			ids = append(ids, app.ID)
		}
	}
	slices.Sort(ids)
	var out []string
	switch len(ids) {
	case 0:
	case 1:
		out = append(out, fmt.Sprintf("ct mark and 0x%x == %d", AppMask, ids[0]))
	default:
		s := make([]string, len(ids))
		for i, id := range ids {
			s[i] = strconv.Itoa(id)
		}
		out = append(out, fmt.Sprintf("ct mark and 0x%x { %s }", AppMask, strings.Join(s, ", ")))
	}
	if unknown {
		out = append(out, fmt.Sprintf("ct mark and 0x%x == 0x%x", AppMask|AppDoneBit, AppDoneBit))
	}
	return out, nil
}

// appModeLines compiles one expansion of a rule when the rule base has
// application rules (connections are re-evaluated until their application
// is settled). match holds the rule's zone/address/service terms.
//
//   - allow: logs once (the logged bit), writes the rule into the ct mark
//     (its tag: appidd's end log and the IPS profile; zero clears what an
//     earlier evaluation wrote), and accepts: at once and final when no
//     application rule comes before it (nothing can shift), otherwise via
//     the allowed chain, final only when the application is settled. An
//     application rule also lets a connection through while its
//     application isn't known yet, unfinalised, so the handshake passes:
//     for at most AppPendingPackets packets, and tagged with the rule, so
//     the rule's IPS profile inspects those packets too.
//   - deny/reset: drops (or resets) and marks the connection denied, so
//     the rest of it is dropped at the top of the chain without logging
//     again. An application rule only matches once the application is known.
func (c *compiler) appModeLines(r config.Rule, match []string, v verdict, appMatches []string) []string {
	comment := fmt.Sprintf("comment \"rule:%s\"", r.Name)
	join := func(parts ...[]string) string {
		var all []string
		for _, p := range parts {
			all = append(all, p...)
		}
		return strings.Join(all, " ")
	}
	terms := [][]string{nil}
	if len(appMatches) > 0 {
		terms = nil
		for _, m := range appMatches {
			terms = append(terms, []string{m})
		}
	}
	logStmt := fmt.Sprintf("log prefix \"ngfw %s %s \"", r.Name, r.Action)
	var lines []string
	if r.Action != "allow" {
		for _, t := range terms {
			stmts := []string{"counter"}
			if r.Log {
				stmts = append(stmts, logStmt)
			}
			stmts = append(stmts, fmt.Sprintf("ct mark set ct mark or 0x%x", DeniedBit), v.verdict, comment)
			lines = append(lines, join(match, t, stmts))
		}
		return lines
	}
	tag := c.ruleTag(r)
	for _, t := range terms {
		if r.Log {
			lines = append(lines, join(match, t, []string{fmt.Sprintf("ct mark and 0x%x == 0", LoggedBit), logStmt,
				fmt.Sprintf("ct mark set ct mark or 0x%x", LoggedBit)}))
		}
		stmts := []string{"counter"}
		switch {
		case c.ruleIdx < c.firstApp:
			// Above every application rule: nothing can shift; final now.
			stmts = append(stmts, fmt.Sprintf("ct mark set ct mark and 0x%08x or 0x%08x", keepLow, tag|FinalBit), "accept")
		default:
			// Always rewrite the rule bits: a connection re-evaluated here may
			// carry another rule's tag from an earlier packet.
			stmts = append(stmts, fmt.Sprintf("ct mark set ct mark and 0x%08x or 0x%08x", keepLow, tag), "jump allowed")
		}
		lines = append(lines, join(match, t, append(stmts, comment)))
	}
	if len(appMatches) > 0 {
		// Application not known yet: let it through, not final, so the
		// rule base sees the connection again once App Identification has named it.
		// Bounded (AppPendingPackets) and tagged with the rule, so its IPS
		// profile sees these packets.
		lines = append(lines, join(match, []string{fmt.Sprintf("ct mark and 0x%x == 0", AppMask|AppDoneBit),
			fmt.Sprintf("ct packets < %d", AppPendingPackets), "counter",
			fmt.Sprintf("ct mark set ct mark and 0x%08x or 0x%08x", keepLow, tag), "accept",
			fmt.Sprintf("comment \"rule:%s (application pending)\"", r.Name)}))
	}
	return lines
}

// input protects the firewall itself. Interfaces in a zone may only ping it
// and receive replies to its own traffic; management services (SSH, the tag
// API) are reachable only on interfaces outside any zone, i.e. mgmt.
func (c *compiler) input(b *strings.Builder) {
	var plain, vrf []string
	for _, in := range c.cfg.Interfaces {
		if in.Zone == "" {
			continue
		}
		if c.inVRF[in.Name] {
			vrf = appendUnique(vrf, fmt.Sprintf("%q", in.Name))
		} else {
			plain = appendUnique(plain, fmt.Sprintf("%q", in.Name))
		}
	}
	var zoned []string // match expressions for "from a zoned interface"
	if len(plain) > 0 {
		zoned = append(zoned, "iifname "+set(plain))
	}
	if len(vrf) > 0 {
		zoned = append(zoned, "meta sdifname "+set(vrf))
	}
	b.WriteString("\n\tchain input {\n")
	b.WriteString("\t\ttype filter hook input priority filter; policy accept;\n")
	b.WriteString("\t\tiif lo accept\n")
	b.WriteString("\t\tct state established,related accept\n")
	b.WriteString("\t\tct state invalid drop\n")
	c.trunkDrop(b, false)
	// Routing protocols reach the firewall only from what's configured:
	// BGP from each neighbor's address, OSPF on each OSPF interface.
	for _, n := range c.cfg.BGPNeighbors {
		fmt.Fprintf(b, "\t\tip saddr %s tcp dport 179 accept comment \"bgp:%s\"\n", n.Address, n.Name)
	}
	for _, o := range c.cfg.OSPFInterfaces {
		match := "iifname"
		if c.inVRF[o.Name] {
			match = "meta sdifname"
		}
		fmt.Fprintf(b, "\t\t%s %q meta l4proto 89 accept comment \"ospf:%s\"\n", match, o.Name, o.Name)
	}
	// DHCP requests on each interface the firewall serves DHCP on.
	for _, s := range c.cfg.DHCPServers {
		match := "iifname"
		if c.inVRF[s.Name] {
			match = "meta sdifname"
		}
		fmt.Fprintf(b, "\t\t%s %q udp dport 67 accept comment \"dhcp:%s\"\n", match, s.Name, s.Name)
	}
	for _, z := range zoned {
		fmt.Fprintf(b, "\t\t%s meta l4proto icmp accept\n", z)
	}
	if c.decryptOn() {
		// Connections handed to tlsd (chain decrypt) arrive here.
		fmt.Fprintf(b, "\t\tmeta mark and 0x%x != 0 meta l4proto tcp accept comment \"decryption\"\n", DecryptMark)
	}
	for _, z := range zoned {
		fmt.Fprintf(b, "\t\t%s counter drop comment \"zone-to-firewall\"\n", z)
	}
	b.WriteString("\t}\n")
}

type verdict struct{ match, verdict string }

func verdicts(action string, svc *svcTerm) []verdict {
	switch action {
	case "allow":
		return []verdict{{verdict: "accept"}}
	case "deny":
		return []verdict{{verdict: "drop"}}
	}
	// reset: TCP gets a reset; everything else an ICMP admin-prohibited.
	if svc != nil {
		if svc.proto == "tcp" {
			return []verdict{{verdict: "reject with tcp reset"}}
		}
		return []verdict{{verdict: "reject with icmpx type admin-prohibited"}}
	}
	return []verdict{
		{match: "meta l4proto tcp", verdict: "reject with tcp reset"},
		{verdict: "reject with icmpx type admin-prohibited"},
	}
}

func elements(es []TagEntry) string {
	sorted := append([]TagEntry(nil), es...)
	sort.Slice(sorted, func(i, j int) bool { return sorted[i].IP.Less(sorted[j].IP) })
	var parts []string
	for _, e := range sorted {
		if !e.IP.Is4() {
			continue
		}
		if e.Remaining > 0 {
			parts = append(parts, fmt.Sprintf("%s timeout %ds", e.IP, int(e.Remaining.Seconds()+0.999)))
		} else {
			parts = append(parts, e.IP.String())
		}
	}
	return strings.Join(parts, ", ")
}

func prefix(s string) (string, error) {
	if p, err := netip.ParsePrefix(s); err == nil {
		if !p.Addr().Is4() {
			return "", fmt.Errorf("IPv6 is not supported yet: %s", s)
		}
		return p.Masked().String(), nil
	}
	a, err := netip.ParseAddr(s)
	if err != nil {
		return "", err
	}
	if !a.Is4() {
		return "", fmt.Errorf("IPv6 is not supported yet: %s", s)
	}
	return a.String(), nil
}

func isAny(vals []string) bool {
	return len(vals) == 0 || (len(vals) == 1 && vals[0] == config.Any)
}

func contains(xs []string, s string) bool {
	for _, x := range xs {
		if x == s {
			return true
		}
	}
	return false
}

func appendUnique(xs []string, s string) []string {
	if contains(xs, s) {
		return xs
	}
	return append(xs, s)
}

func sortedKeys(m map[string]string) []string {
	ks := make([]string, 0, len(m))
	for k := range m {
		ks = append(ks, k)
	}
	sort.Strings(ks)
	return ks
}

// ctZones gives each VRF its own conntrack zone, so the same addresses in
// two VRFs are tracked as different connections. Interfaces in the default
// VRF stay in zone 0; with no VRFs the chain is left out entirely.
func (c *compiler) ctZones(b *strings.Builder) {
	zone := map[string]int{}
	for i, v := range c.cfg.VRFs {
		zone[v.Name] = i + 1
	}
	var elems []string
	for _, in := range c.cfg.Interfaces {
		if z, ok := zone[in.VRFOf()]; ok {
			elems = append(elems, fmt.Sprintf("%q : %d", in.Name, z))
		}
	}
	if len(elems) == 0 {
		return
	}
	b.WriteString("\n\tchain vrf_zones {\n")
	b.WriteString("\t\ttype filter hook prerouting priority raw; policy accept;\n")
	fmt.Fprintf(b, "\t\tct zone set iifname map { %s }\n", strings.Join(elems, ", "))
	var marks []string
	for _, in := range c.cfg.Interfaces {
		if m, ok := c.vrfMark[in.Name]; ok {
			marks = append(marks, fmt.Sprintf("%q : 0x%x", in.Name, m))
		}
	}
	fmt.Fprintf(b, "\t\tmeta mark set iifname map { %s }\n", strings.Join(marks, ", "))
	b.WriteString("\t}\n")
}

// ruleTag is what an allow rule writes into the ct mark: its position + 1
// when appidd should log the session's end (logged, App Identification on; with the
// session bit) or the IPS inspects its traffic. 0: nothing.
func (c *compiler) ruleTag(r config.Rule) int {
	if r.Action != "allow" {
		return 0
	}
	tag := 0
	if r.Log && c.cfg.System.AppIDOn() {
		tag = (c.ruleIdx+1)<<RuleShift | SessionBit
	}
	if r.IPSProfile != "" && c.cfg.IPSActive() {
		tag |= (c.ruleIdx + 1) << RuleShift
	}
	return tag
}

// ips writes the IPS chains: allowed traffic of rules with a profile goes
// to Suricata (NFQUEUE 2-3, bypass: it flows when Suricata is down), which
// marks packets that match a signature with its severity; ips_enforce then
// drops what the rule's profile blocks and marks the connection denied, so
// the forward chain drops the rest of it.
func (c *compiler) ips(b *strings.Builder) {
	if len(c.ipsRules) == 0 {
		return
	}
	var tags []string
	profiles := map[string]int{}
	var order []string
	for _, r := range c.ipsRules {
		tags = append(tags, fmt.Sprintf("0x%08x", r.tag))
		if _, ok := profiles[r.profile]; !ok {
			profiles[r.profile] = len(order)
			order = append(order, r.profile)
		}
	}
	b.WriteString("\n\tchain ips {\n")
	b.WriteString("\t\ttype filter hook forward priority filter + 10; policy accept;\n")
	match := "== " + tags[0]
	if len(tags) > 1 {
		match = set(tags)
	}
	fmt.Fprintf(b, "\t\tmeta nfproto ipv4 ct mark and 0xffff0000 %s queue flags bypass,fanout to 2-3 comment \"ips\"\n", match)
	b.WriteString("\t}\n")
	for i, name := range order {
		p, _ := c.cfg.IPSProfile(name)
		fmt.Fprintf(b, "\n\tchain ips_p%d {\n", i)
		fmt.Fprintf(b, "\t\tcomment \"ips profile %s\"\n", name)
		for _, sev := range config.IPSSeverities {
			if p.Action(sev) == config.IPSBlock {
				fmt.Fprintf(b, "\t\tmeta mark and 0x%08x != 0 ct mark set ct mark or 0x%x counter drop comment \"ips:%s %s\"\n",
					IPSSeverityMark(sev), DeniedBit, name, sev)
			}
		}
		b.WriteString("\t}\n")
	}
	b.WriteString("\n\tchain ips_enforce {\n")
	b.WriteString("\t\ttype filter hook forward priority filter + 20; policy accept;\n")
	fmt.Fprintf(b, "\t\tmeta mark and 0x%08x == 0 accept\n", IPSMarkMask)
	var vm []string
	for _, r := range c.ipsRules {
		vm = append(vm, fmt.Sprintf("0x%08x : jump ips_p%d", r.tag, profiles[r.profile]))
	}
	fmt.Fprintf(b, "\t\tct mark and 0xffff0000 vmap { %s }\n", strings.Join(vm, ", "))
	fmt.Fprintf(b, "\t\tmeta mark set meta mark and 0x%08x\n", ^uint32(IPSMarkMask))
	b.WriteString("\t}\n")
}

// trunkDrop drops untagged traffic on trunk-only interfaces (no zone, not
// management): their VLAN subinterfaces carry the traffic, and the trunk
// itself is in no zone, so nothing may enter or leave on it untagged. A
// VLAN's packets show its own name (inside.150), never the trunk's.
// forward also drops traffic routed out of a trunk.
func (c *compiler) trunkDrop(b *strings.Builder, forward bool) {
	var ts []string
	for _, t := range c.cfg.Trunks() {
		ts = append(ts, fmt.Sprintf("%q", t))
	}
	if len(ts) == 0 {
		return
	}
	fmt.Fprintf(b, "\t\tiifname %s counter drop comment \"trunk: untagged\"\n", set(ts))
	if forward {
		fmt.Fprintf(b, "\t\toifname %s counter drop comment \"trunk: untagged\"\n", set(ts))
	}
}
