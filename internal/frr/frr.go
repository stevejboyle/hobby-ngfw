// Package frr turns the SJB-OS routing config into FRRouting
// configuration, applies it, and reads routing status back. ngfwd owns
// /etc/frr/frr.conf and the bgpd/ospfd lines of /etc/frr/daemons; operators
// never run vtysh.
package frr

import (
	"fmt"
	"strings"

	"github.com/stevejboyle/hobby-ngfw/internal/config"
)

// Result is the compiled FRR configuration.
type Result struct {
	Conf    string          // frr.conf
	Daemons map[string]bool // bgpd, ospfd: on or off
}

// Enabled reports whether any routing protocol is configured.
func (r *Result) Enabled() bool { return r.Daemons["bgpd"] || r.Daemons["ospfd"] }

// frrVRF is FRR's name for a SJB-OS VRF: the kernel device name.
func frrVRF(vrf string) string { return config.VRFDevice(vrf) }

func vrfSuffix(vrf string) string {
	if d := frrVRF(vrf); d != "" {
		return " vrf " + d
	}
	return ""
}

// redistKey maps SJB-OS redistribution sources to FRR's. SJB-OS static
// routes are kernel routes installed by ngfwd, so FRR knows them as kernel.
func redistKey(src string) string {
	if src == config.RedistStatic {
		return "kernel"
	}
	return src
}

// Compile builds frr.conf from a validated config.
func Compile(c *config.Config) *Result {
	res := &Result{Daemons: map[string]bool{"bgpd": false, "ospfd": false}}
	var b strings.Builder
	b.WriteString("! Generated by SJB-OS (ngfwd). Do not edit; changes are replaced on commit.\n")
	b.WriteString("frr defaults traditional\n")
	host := c.System.Hostname
	if host == "" {
		host = "sjb-fw"
	}
	fmt.Fprintf(&b, "hostname %s\n", host)
	b.WriteString("log syslog informational\n")
	b.WriteString("service integrated-vtysh-config\n!\n")

	for _, pl := range c.PrefixLists {
		for i, e := range pl.Entries {
			action, prefix, ge, le, _ := config.ParsePrefixEntry(e)
			line := fmt.Sprintf("ip prefix-list %s seq %d %s %s", pl.Name, (i+1)*5, action, prefix)
			if ge > 0 {
				line += fmt.Sprintf(" ge %d", ge)
			}
			if le > 0 {
				line += fmt.Sprintf(" le %d", le)
			}
			b.WriteString(line + "\n")
		}
		b.WriteString("!\n")
	}

	for _, o := range c.OSPFInterfaces {
		area, _ := config.NormalizeArea(o.Area)
		fmt.Fprintf(&b, "interface %s\n", o.Name)
		fmt.Fprintf(&b, " ip ospf area %s\n", area)
		if o.Cost > 0 {
			fmt.Fprintf(&b, " ip ospf cost %d\n", o.Cost)
		}
		if o.Passive {
			b.WriteString(" ip ospf passive\n")
		}
		b.WriteString("exit\n!\n")
	}

	for _, r := range c.Routing {
		if r.BGPASN == 0 {
			continue
		}
		res.Daemons["bgpd"] = true
		fmt.Fprintf(&b, "router bgp %d%s\n", r.BGPASN, vrfSuffix(r.Name))
		fmt.Fprintf(&b, " bgp router-id %s\n", r.RouterID)
		// SJB-OS semantics: no import/export list means accept and send
		// everything, and listed networks are announced as configured.
		b.WriteString(" no bgp ebgp-requires-policy\n")
		b.WriteString(" no bgp network import-check\n")
		var nbrs []config.BGPNeighbor
		for _, n := range c.BGPNeighbors {
			if n.VRFOf() == r.Name {
				nbrs = append(nbrs, n)
			}
		}
		for _, n := range nbrs {
			fmt.Fprintf(&b, " neighbor %s remote-as %d\n", n.Address, n.RemoteAS)
			desc := n.Name
			if n.Description != "" {
				desc += " - " + n.Description
			}
			fmt.Fprintf(&b, " neighbor %s description %s\n", n.Address, desc)
		}
		b.WriteString(" !\n address-family ipv4 unicast\n")
		for _, net := range r.BGPNetworks {
			fmt.Fprintf(&b, "  network %s\n", net)
		}
		for _, src := range r.BGPRedistribute {
			fmt.Fprintf(&b, "  redistribute %s\n", redistKey(src))
		}
		for _, n := range nbrs {
			if n.NextHopSelf {
				fmt.Fprintf(&b, "  neighbor %s next-hop-self\n", n.Address)
			}
			if n.Import != "" {
				fmt.Fprintf(&b, "  neighbor %s prefix-list %s in\n", n.Address, n.Import)
			}
			if n.Export != "" {
				fmt.Fprintf(&b, "  neighbor %s prefix-list %s out\n", n.Address, n.Export)
			}
		}
		b.WriteString(" exit-address-family\nexit\n!\n")
	}

	for _, r := range c.Routing {
		if !r.OSPF {
			continue
		}
		res.Daemons["ospfd"] = true
		fmt.Fprintf(&b, "router ospf%s\n", vrfSuffix(r.Name))
		fmt.Fprintf(&b, " ospf router-id %s\n", r.RouterID)
		for _, src := range r.OSPFRedistribute {
			fmt.Fprintf(&b, " redistribute %s\n", redistKey(src))
		}
		b.WriteString("exit\n!\n")
	}
	b.WriteString("end\n")
	res.Conf = b.String()
	return res
}

// SetDaemons rewrites the bgpd= and ospfd= lines of an FRR daemons file,
// leaving everything else as Debian shipped it. It reports whether
// anything changed (FRR must then restart, not just reload).
func SetDaemons(file string, want map[string]bool) (string, bool) {
	lines := strings.Split(file, "\n")
	changed := false
	seen := map[string]bool{}
	for i, l := range lines {
		for d, on := range want {
			if strings.HasPrefix(l, d+"=") {
				seen[d] = true
				v := d + "=no"
				if on {
					v = d + "=yes"
				}
				if l != v {
					lines[i] = v
					changed = true
				}
			}
		}
	}
	for _, d := range []string{"bgpd", "ospfd"} {
		if on, ok := want[d]; ok && !seen[d] {
			v := d + "=no"
			if on {
				v = d + "=yes"
			}
			lines = append(lines, v)
			changed = true
		}
	}
	return strings.Join(lines, "\n"), changed
}
