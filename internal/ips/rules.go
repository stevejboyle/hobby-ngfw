// Package ips runs SJB-OS's intrusion prevention: Suricata inline on
// NFQUEUE with the Emerging Threats Open signatures. It downloads and
// prepares the signatures, keeps the engine's status, and turns Suricata's
// alerts into threat log entries.
//
// Suricata never drops anything itself: every signature is an alert, and
// SJB-OS appends nfq_set_mark so a matching packet leaves Suricata with
// its severity in the packet mark. The firewall's ips_enforce chain then
// blocks or passes it by the rule's IPS profile (see internal/compiler).
package ips

import (
	"bufio"
	"bytes"
	"fmt"
	"regexp"
	"sort"
	"strconv"
	"strings"

	"github.com/stevejboyle/sjb-os/internal/compiler"
)

var (
	sidRE      = regexp.MustCompile(`\bsid\s*:\s*(\d+)\s*;`)
	severityRE = regexp.MustCompile(`\bsignature_severity\s+([A-Za-z_]+)`)
	actionRE   = regexp.MustCompile(`^(alert|drop|reject|rejectsrc|rejectdst|rejectboth|pass)\s`)
)

// Severity normalises ET's signature_severity: critical, major, minor or
// informational (anything else, Unknown included).
func Severity(s string) string {
	switch strings.ToLower(s) {
	case "critical":
		return "critical"
	case "major":
		return "major"
	case "minor":
		return "minor"
	}
	return "informational"
}

// TestSignatures are SJB-OS's own: payloads containing SJB-IPS-TEST-
// <LEVEL> match at that severity, so a profile can be checked from any
// client (tools/ips-test.sh).
var TestSignatures = []struct {
	SID      int
	Severity string
	Content  string
}{
	{9900001, "critical", "SJB-IPS-TEST-CRITICAL"},
	{9900002, "major", "SJB-IPS-TEST-MAJOR"},
	{9900003, "minor", "SJB-IPS-TEST-MINOR"},
	{9900004, "informational", "SJB-IPS-TEST-INFO"},
}

// Counts are signatures per severity.
type Counts map[string]int

// Total is the number of signatures.
func (c Counts) Total() int {
	n := 0
	for _, v := range c {
		n += v
	}
	return n
}

// Tuning is what the config changes in the rules file: signatures left
// out, and the exception code of each signature with IPS exceptions
// (compiler.IPSExceptionCodes).
type Tuning struct {
	Disabled map[int]bool
	Codes    map[int]uint32
}

// mark is the packet mark a match of sid sets: its severity, and its
// exception code or, for a signature without exceptions, the plain bit.
func (t Tuning) mark(sid int, severity string) uint32 {
	m := compiler.IPSSeverityMark(severity)
	if c, ok := t.Codes[sid]; ok {
		return m | c
	}
	return m | compiler.IPSPlainBit
}

// Process prepares rule files for Suricata: enabled rules only (commented
// ones stay out), minus disabled SIDs, every action turned into alert
// except pass, and nfq_set_mark with the severity (and exception code or
// plain bit) appended. SJB-OS's test signatures come first. files maps
// file names to contents; only *.rules files are read.
func Process(files map[string][]byte, tu Tuning) ([]byte, Counts) {
	disabled := tu.Disabled
	var out bytes.Buffer
	counts := Counts{}
	out.WriteString("# Generated by SJB-OS from Emerging Threats Open. Do not edit.\n")
	for _, t := range TestSignatures {
		if disabled[t.SID] {
			continue
		}
		m := tu.mark(t.SID, t.Severity)
		fmt.Fprintf(&out, "alert ip any any -> any any (msg:\"SJB-OS IPS test signature (%s)\"; content:\"%s\"; nfq_set_mark:0x%08x/0x%08x; sid:%d; rev:1; metadata:signature_severity %s;)\n",
			t.Severity, t.Content, m, m, t.SID, t.Severity)
		counts[t.Severity]++
	}
	var names []string
	for n := range files {
		if strings.HasSuffix(n, ".rules") {
			names = append(names, n)
		}
	}
	sort.Strings(names)
	seen := map[int]bool{}
	for _, n := range names {
		sc := bufio.NewScanner(bytes.NewReader(files[n]))
		sc.Buffer(make([]byte, 64*1024), 4<<20)
		for sc.Scan() {
			line := strings.TrimSpace(sc.Text())
			am := actionRE.FindStringSubmatch(line)
			if am == nil || !strings.HasSuffix(line, ")") {
				continue // comments, disabled rules, blank lines
			}
			sm := sidRE.FindStringSubmatch(line)
			if sm == nil {
				continue
			}
			sid, _ := strconv.Atoi(sm[1])
			if disabled[sid] || seen[sid] {
				continue
			}
			seen[sid] = true
			if am[1] != "pass" && am[1] != "alert" {
				line = "alert" + line[len(am[1]):]
			}
			sev := "informational"
			if m := severityRE.FindStringSubmatch(line); m != nil {
				sev = Severity(m[1])
			}
			if am[1] != "pass" {
				mark := tu.mark(sid, sev)
				line = strings.TrimSuffix(line, ")")
				line = strings.TrimRight(line, " ")
				if !strings.HasSuffix(line, ";") {
					line += ";"
				}
				line += fmt.Sprintf(" nfq_set_mark:0x%08x/0x%08x;)", mark, mark)
			}
			out.WriteString(line)
			out.WriteByte('\n')
			counts[sev]++
		}
	}
	return out.Bytes(), counts
}

// Disabled turns the config's signature ID strings into a set.
func Disabled(sids []string) map[int]bool {
	m := map[int]bool{}
	for _, s := range sids {
		if n, err := strconv.Atoi(strings.TrimSpace(s)); err == nil {
			m[n] = true
		}
	}
	return m
}
